from datetime import timezone

from flask import render_template

from .email import send_email


EMAIL_SUBJECT = "⚠ Dengue Risk Alert – Immediate Attention Required"


def render_prediction_alert(user, prediction):
    generated_on = prediction.prediction_time
    if generated_on.tzinfo is None:
        generated_on = generated_on.replace(tzinfo=timezone.utc)
    generated_on = generated_on.astimezone(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    risk_level = prediction.prediction.removesuffix(" Risk").upper()
    risk_colors = {
        "LOW": "#16803c",
        "MODERATE": "#b77908",
        "MEDIUM": "#b77908",
        "HIGH": "#c2410c",
        "VERY HIGH": "#b91c1c",
    }
    climate = (
        f"Temperature: {prediction.temperature:g}°C\n"
        f"Humidity: {prediction.humidity:g}%\n"
        f"Rainfall: {prediction.rainfall:g} mm"
    )
    recommendations = prediction.recommendations or [
        "Remove stagnant water nearby.",
        "Use mosquito repellent.",
        "Visit a nearby hospital if symptoms worsen.",
    ]
    plain_text = (
        f"Hello {user.full_name},\n\n"
        "Your recent dengue prediction has been completed.\n\n"
        f"Risk Level: {risk_level}\n"
        f"Confidence: {prediction.confidence:g}%\n\n"
        f"Current Climate\n{climate}\n\n"
        "Recommendations\n"
        + "\n".join(f"- {item}" for item in recommendations)
        + f"\n\nGenerated On\n{generated_on}\n\n"
        "This alert was automatically generated by the Dengue Forecasting System."
    )
    html_body = render_template(
        "emails/dengue_alert.html",
        user_name=user.full_name,
        risk_level=risk_level,
        confidence=f"{prediction.confidence:g}",
        risk_color=risk_colors.get(risk_level, "#c2410c"),
        temperature=f"{prediction.temperature:g}",
        humidity=f"{prediction.humidity:g}",
        rainfall=f"{prediction.rainfall:g}",
        recommendations=recommendations,
        generated_on=generated_on,
    )
    return plain_text, html_body


def send_prediction_alert(user, prediction, recipient):
    plain_text, html_body = render_prediction_alert(user, prediction)
    send_email(recipient, EMAIL_SUBJECT, plain_text, html_body=html_body)


def send_daily_summary(user, recipient, message):
    html_body = render_template(
        "emails/daily_summary.html",
        user_name=user.full_name,
        message=message,
    )
    send_email(recipient, "Your DengueWatch daily summary", message, html_body=html_body)


def send_mosquito_detection_alert(user, detection, recipient):
    risk_colors = {
        "High Risk Breeding Site": "#b91c1c",
        "Medium Risk Breeding Site": "#c2410c",
        "Low Risk": "#b77908",
        "No Breeding Site Detected": "#16803c",
    }
    message = (
        f"Hello {user.full_name},\n\n"
        "A high-risk mosquito breeding site was detected in your image.\n\n"
        f"Prediction: {detection.prediction}\n"
        f"Confidence: {detection.confidence:.2f}%\n"
        f"Detected objects: {', '.join(detection.objects_detected or []) or 'None'}\n\n"
        "Recommendations:\n"
        + "\n".join(f"- {item}" for item in detection.recommendation or [])
        + "\n\nThis automated result is informational; follow local public-health guidance."
    )
    html_body = render_template(
        "emails/mosquito_detection_alert.html",
        user_name=user.full_name,
        prediction=detection.prediction,
        confidence=f"{detection.confidence:.2f}",
        risk_color=risk_colors[detection.prediction],
        objects_detected=detection.objects_detected or [],
        recommendations=detection.recommendation or [],
    )
    send_email(
        recipient,
        "⚠ Mosquito Breeding Site Alert – Immediate Attention Required",
        message,
        html_body=html_body,
    )
